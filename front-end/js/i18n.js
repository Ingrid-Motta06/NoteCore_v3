/**
 * Devolve o texto traduzido para a chave, no idioma atual (window.getLang()).
 * Aceita variáveis para interpolação: t("note.updatedDaysAgo", { n: 3 })
 */
function t(key, vars) {
  const lang = (typeof getLang === "function") ? getLang() : "pt";
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.pt;
  let str = dict[key] != null ? dict[key] : (TRANSLATIONS.pt[key] || key);
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = str.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
    });
  }
  return str;
}

/** Rótulo de categoria traduzido, com fallback para o valor original. */
function categoryLabel(cat) {
  if (!cat) return t("note.noCategory");
  const lang = (typeof getLang === "function") ? getLang() : "pt";
  const map = CATEGORY_LABELS[lang];
  return (map && map[cat]) || cat;
}
